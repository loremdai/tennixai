"""Canonical P3 prediction domain models.

The independent prediction layer reads tennis data only. It must never import
from ``app.markets`` and never consume current or future market prices, order
books or resolutions. Probabilities are calibrated, versioned and carry
structured evidence; abstention is a typed, first-class result.
"""

import math
from enum import StrEnum

from pydantic import AwareDatetime, Field, model_validator

from app.domain import FrozenModel


class ModelAvailability(StrEnum):
    AVAILABLE = "available"
    DEGRADED = "degraded"
    UNPROMOTED = "unpromoted"
    UNAVAILABLE = "unavailable"


class ProbabilityEstimate(FrozenModel):
    player_id: str = Field(min_length=1)
    probability: float = Field(ge=0.0, le=1.0)
    lower: float = Field(ge=0.0, le=1.0)
    upper: float = Field(ge=0.0, le=1.0)

    @model_validator(mode="after")
    def validate_interval(self) -> "ProbabilityEstimate":
        if not self.lower <= self.probability <= self.upper:
            raise ValueError("probability must lie within [lower, upper]")
        return self


class PredictionEvidence(FrozenModel):
    """Structured explanation item generated by the model/feature engine."""

    code: str = Field(min_length=1)
    description: str = Field(min_length=1)
    value: float | None = None


class PredictionSnapshot(FrozenModel):
    match_id: str = Field(min_length=1)
    outcomes: tuple[ProbabilityEstimate, ...] = ()
    availability: ModelAvailability
    abstain_reason: str | None = None
    model_version: str = Field(min_length=1)
    calibration_version: str = Field(min_length=1)
    data_version: str = Field(min_length=1)
    input_state_version: int = Field(ge=0)
    evidence: tuple[PredictionEvidence, ...] = ()
    as_of: AwareDatetime

    @model_validator(mode="after")
    def validate_shape(self) -> "PredictionSnapshot":
        if len(self.outcomes) not in (0, 2):
            raise ValueError("prediction carries either zero or exactly two outcomes")
        if self.availability in (
            ModelAvailability.AVAILABLE,
            ModelAvailability.DEGRADED,
        ):
            if len(self.outcomes) != 2:
                raise ValueError(
                    f"{self.availability.value} prediction requires two calibrated outcomes"
                )
            if self.abstain_reason is not None:
                raise ValueError(
                    f"{self.availability.value} prediction must not carry abstain_reason"
                )
        else:
            if len(self.outcomes) != 0:
                raise ValueError(
                    f"{self.availability.value} prediction must abstain without probabilities"
                )
            if not self.abstain_reason:
                raise ValueError(
                    f"{self.availability.value} prediction requires a typed abstain_reason"
                )
        if len(self.outcomes) == 2:
            first, second = self.outcomes
            if first.player_id == second.player_id:
                raise ValueError(
                    "prediction outcomes must reference two distinct players"
                )
            total = first.probability + second.probability
            if not math.isclose(total, 1.0, abs_tol=1e-9):
                raise ValueError(
                    f"model probabilities must be complementary (sum=1.0), got {total}"
                )
        return self
